def V4_module(A, F, n, J, which='alpha'):
    """V_(n, alpha) (Theorem 4.3.x (ii), J a Jordan block) or V_(n, infinity)
    (type (iii)), for the generators (1,2) and (3,4) of V4."""
    I = identity_matrix(F, n)
    Z = zero_matrix(F, n)
    if which == 'alpha':
        x = block_matrix([[I, I], [Z, I]], subdivide=False)
        y = block_matrix([[I, J], [Z, I]], subdivide=False)
    else:
        J0 = zero_matrix(F, n)
        for i in range(n - 1):
            J0[i, i + 1] = 1
        x = block_matrix([[I, J0], [Z, I]], subdivide=False)
        y = block_matrix([[I, I], [Z, I]], subdivide=False)
    return Mod(A, [x, y])


def jordan(F, n, a):
    J = a * identity_matrix(F, n)
    for i in range(n - 1):
        J[i, i + 1] = 1
    return J


def ar_data(ctx, N):
    M, E, iota, sigma, soc = ar_sequence(ctx, N)
    return M, decompose(E), soc


def alt_word(c, n):
    """The alternating word of n direct letters starting with c."""
    out = []
    for i in range(n):
        out.append((c if i % 2 == 0 else other(c), 1))
    return tuple(out)


def L_q(C, q):
    A = alt_word('a', 2 * q - 1)
    B = alt_word('b', 2 * q - 1)
    for pre in (concat(A, letters('b^-1')), concat(B, letters('a^-1'))):
        if not is_empty(C) and C[:len(pre)] == pre:
            rest = C[len(pre):]
            return rest if rest else (ONE_A if pre[-1][0] == 'b' else ONE_B)
    for cand in (concat(winv(A), letters('b'), C),
                 concat(winv(B), letters('a'), C)):
        if cand is not None:
            return cand
    raise ValueError


def R_q(C, q):
    return winv(L_q(winv(C), q))


def check_LR_words(q, maxlen):
    """Example (iii) after Theorem 4.17.4, corrected: on the set W_q of
    words of modules of the first kind for D_4q (no (ab)^q, (ba)^q or
    inverses), L_q is a bijection from W_q minus {A, B} onto W_q minus
    {A^-1, B^-1}, R_q one from W_q minus {A^-1, B^-1} onto W_q minus
    {A, B}, and L_q R_q = R_q L_q on W_q minus {A^+-1, B^+-1}.  Words up
    to length maxlen; onto: words up to length maxlen - 2q.  Commutation
    for longer words: L_q changes only the first 2q letters (removed or
    prepended) and R_q only the last 2q, so for length >= 4q they act on
    disjoint ends."""
    tag = 'D_%d' % (4 * q)
    Aw, Bw = alt_word('a', 2 * q - 1), alt_word('b', 2 * q - 1)
    Ai, Bi = winv(Aw), winv(Bw)
    f_words = [wpow(letters('a b'), q), wpow(letters('b a'), q)]
    f_words += [winv(fw) for fw in f_words]

    def ok_word(C):
        return is_empty(C) or not any(contains(C, fw) for fw in f_words)
    valid = [ONE_A, ONE_B] + [C for n in range(1, maxlen + 1)
                              for C in all_words(n) if ok_word(C)]
    for f, src, tgt in ((lambda C: L_q(C, q), (Aw, Bw), (Ai, Bi)),
                        (lambda C: R_q(C, q), (Ai, Bi), (Aw, Bw))):
        img = {}
        into = True
        for C in valid:
            if C in src:
                continue
            X = f(C)
            into = into and ok_word(X) and X not in tgt
            img.setdefault(X, []).append(C)
        onto = all(Dw in img for Dw in valid
                   if wlen(Dw) <= maxlen - 2 * q and Dw not in tgt)
        check(into and all(len(v) == 1 for v in img.values()) and onto and
              all(not ok_word(f(C)) for C in src),
              tag + ': L_q (and R_q) restrict to bijections between the '
              'words of modules of the first kind other than A, B and '
              'those other than A^-1, B^-1 (resp. the other way round); '
              'L_q(A), L_q(B) (R_q(A^-1), R_q(B^-1)) are not such words '
              '(lengths <= %d)' % maxlen)
    special = (Aw, Bw, Ai, Bi)
    check(all(L_q(R_q(C, q), q) == R_q(L_q(C, q), q) for C in valid
              if C not in special),
          tag + ': L_q R_q = R_q L_q on these words other than A^+-1, '
          'B^+-1 (lengths <= %d)' % maxlen)
    refuted(all(L_q(R_q(C, q), q) == R_q(L_q(C, q), q) for C in special),
            tag + ': printed L_q R_q = R_q L_q on all words (fails at A)')
    refuted(L_q(ONE_A, q) != L_q(concat(Aw, letters('b^-1'),
                                        L_q(ONE_A, q)), q),
            tag + ': printed: L_q is a bijection of the set W of all words '
            '(L_q(1_a) = L_q(A b^-1 A^-1 b))')


