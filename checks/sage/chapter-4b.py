            mult = {i: blocks.count(i) for i in range(1, n + 1)}
            Fs = {(i, j): F_ij(T, n, i, j) for i in range(0, n + 2)
                  for j in range(0, n + 2)}
            # F_(i+1, n-i) = Ker(T^i) = F_(i,0)
