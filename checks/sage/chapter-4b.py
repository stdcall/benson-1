    # --- Proposition 4.12.10 (restriction to subgroups), k V_4
    # generators: g0 = (3,4) and g1 = (1,2) of V4; words of the subgroups
    sub = {'<g0>': [(0,)], '<g1>': [(1,)], '<g0 g1>': [(0, 1)], '1': [()]}
    k = modsV[0]
    M, E, iota, sigma, soc = ar_sequence(ctxV, k)
