# A word is a tuple of letters (c, e), c in 'ab', e = 1 (direct) or -1
# (inverse); the zero length words are ONE_A = 1_a and ONE_B = 1_b.
ONE_A, ONE_B = ('1', 'a'), ('1', 'b')


def is_empty(C):
    return len(C) == 2 and C[0] == '1'


def wlen(C):
    return 0 if is_empty(C) else len(C)


def start(C):
    """Type of the first letter; 1_a begins with a (p. 136)."""
    return C[1] if is_empty(C) else C[0][0]


def end(C):
    """Type of the last letter; 1_a ends where its inverse 1_b begins."""
    if is_empty(C):
        return 'b' if C[1] == 'a' else 'a'
    return C[-1][0]


def other(c):
    return 'b' if c == 'a' else 'a'


def winv(C):
    if is_empty(C):
        return ONE_B if C[1] == 'a' else ONE_A
    return tuple((c, -e) for (c, e) in reversed(C))


def concat(*Cs):
    """The concatenation, or None if it is not a word."""
    out = Cs[0]
    for D in Cs[1:]:
        if end(out) == start(D):
            return None
        out = D if is_empty(out) else (out if is_empty(D) else out + D)
    return out


def letters(s):
    out = []
    for tok in s.split():
        out.append((tok[0], -1 if tok.endswith('^-1') else 1))
    return tuple(out)


def all_words(n):
    out = []
    for first in [('a', 1), ('a', -1), ('b', 1), ('b', -1)]:
        cur = [(first,)]
        for _ in range(n - 1):
            cur = [w + ((other(w[-1][0]), e),) for w in cur for e in (1, -1)]
        out += cur
    return out


def wstr(C):
    if is_empty(C):
        return '1_' + C[1]
    return ''.join(c + ('' if e == 1 else "'") for c, e in C)


def wpow(C, k):
    return C * k


def rot(C, i):
    return C[i:] + C[:i]


def is_primitive(C):
    n = len(C)
    return all(C != C[d:] + C[:d] for d in range(1, n) if n % d == 0)


def contains(C, sub):
    n, m = len(C), len(sub)
    return any(C[i:i + m] == sub for i in range(n - m + 1))


def string_module(F, C, A=None):
    """M(C) (p. 137): basis z_0, ..., z_n; the letter l_i joins
    z_(i-1) <- z_i; a direct letter maps z_i to z_(i-1), an inverse letter
    maps z_(i-1) to z_i; X acts via a and Y via b."""
    n = wlen(C)
    X, Y = zero_matrix(F, n + 1), zero_matrix(F, n + 1)
    if n:
        for i, (c, e) in enumerate(C, start=1):
            T = X if c == 'a' else Y
            if e == 1:
                T[i - 1, i] = 1
            else:
                T[i, i - 1] = 1
    return Mod(A if A is not None else FreeAlgebraStub(F), [X, Y])


def band_module(F, C, phi, A=None):
    """M(C, phi) (p. 137): V_0, ..., V_(n-1), the letter l_i between V_i and
    V_(i-1) (indices mod n), l_1 = phi and the others the identity, as
    linear relations from V_i to V_(i-1): a direct letter acts from V_i to
    V_(i-1) by the given map, an inverse letter from V_(i-1) to V_i by the
    inverse of the given map."""
    n, m = len(C), phi.nrows()
    X, Y = zero_matrix(F, n * m), zero_matrix(F, n * m)
    I = identity_matrix(F, m)
    phinv = sp(dense(phi).inverse())
    for i, (c, e) in enumerate(C, start=1):
        T = X if c == 'a' else Y
        src, dst = i % n, i - 1
        if e == 1:
            T.set_block(dst * m, src * m, phi if i == 1 else I)
        else:
            T.set_block(src * m, dst * m, phinv if i == 1 else I)
    return Mod(A if A is not None else FreeAlgebraStub(F), [X, Y])


def sinter(U, V):
    F = U.base_ring()
    n = U.nrows()
    if U.ncols() == 0 or V.ncols() == 0:
        return sp(dmatrix(F, n, 0))
    K = dense(U).augment(-dense(V)).right_kernel().basis_matrix()
    if K.nrows() == 0:
        return sp(dmatrix(F, n, 0))
    return colspace(smul(U, K.matrix_from_columns(range(U.ncols()))
                         .transpose()))


def splus(U, V):
    if U.ncols() == 0:
        return V
    if V.ncols() == 0:
        return U
    return colspace(dense(U).augment(dense(V)))


def sdim(U):
    return rank(U)


def subset(U, V):
    return U.ncols() == 0 or sdim(splus(U, V)) == sdim(V)


def same_space(U, V):
    return subset(U, V) and subset(V, U)


class Relations:
    """A module of k<X, Y>/(X^2, Y^2) with words acting on subspaces as
    linear relations, the last letter first (p. 138: C^-(M) = C d M; for
    C = a^-1 b this is the set of m with X m in Y X M), with a cache."""

    def __init__(self, M):
        self.M, self.F, self.n = M, M.A.F, M.dim
        self.cache = {}
        self.whole = identity_matrix(self.F, self.n)
        self.zero = sp(dmatrix(self.F, self.n, 0))

    def letter(self, l, U):
        c, e = l
        T = self.M.mats[0] if c == 'a' else self.M.mats[1]
        if e == 1:
            return colspace(T * U) if U.ncols() else U
        if U.ncols() == 0:
            return kernel_cols(T)
        K = dense(T).augment(-dense(U)).right_kernel().basis_matrix()
        if K.nrows() == 0:
            return self.zero
        return colspace(K.matrix_from_columns(range(self.n)).transpose())

    def apply(self, C, which):
        """C applied to the whole space (which = 1) or to 0 (which = 0)."""
        key = (C, which)
        if key in self.cache:
            return self.cache[key]
        if is_empty(C) or len(C) == 0:
            U = self.whole if which else self.zero
        else:
            U = self.letter(C[0], self.apply(C[1:], which))
        self.cache[key] = U
        return U

    def minus(self, C):
        d = (other(end(C)), 1)
        return self.apply((() if is_empty(C) else C) + (d,), 1)

    def plus(self, C):
        d = (other(end(C)), -1)
        return self.apply((() if is_empty(C) else C) + (d,), 0)

    def S_CD(self, C, D):
        """dim S_(C,D)(M) by the first formula of p. 138 and by the second
        (symmetric) one."""
        Cp, Cm, Dp, Dm = self.plus(C), self.minus(C), self.plus(D), \
            self.minus(D)
        d1 = sdim(sinter(splus(Dp, Cm), Cp)) - sdim(sinter(splus(Dm, Cm), Cp))
        d2 = sdim(sinter(Cp, Dp)) - sdim(splus(sinter(Cp, Dm),
                                               sinter(Cm, Dp)))
        return d1, d2

    def band_part(self, C):
        """C'(M) and C''(M)."""
        lo, hi = self.zero, self.whole
        for _ in range(self.n + 1):
            lo = self._word(C, lo)
            hi = self._word(C, hi)
        return lo, hi

    def _word(self, C, U):
        for l in reversed(C):
            U = self.letter(l, U)
        return U

    def relation(self, C):
        """The relation of C as {(RA c, RB c)}."""
        F, n = self.F, self.n
        I = dense(identity_matrix(F, n))
        RA, RB = I, I
        for (c, e) in reversed(C):
            T = dense(self.M.mats[0] if c == 'a' else self.M.mats[1])
            A2, B2 = (I, T) if e == 1 else (T, I)
            K = RB.augment(-A2).right_kernel().basis_matrix()
            cc = K.matrix_from_columns(range(RB.ncols())).transpose()
            dd = K.matrix_from_columns(range(RB.ncols(), K.ncols())) \
                .transpose()
            RA, RB = dense(smul(RA, cc)), dense(smul(B2, dd))
        return RA, RB

    def S_C(self, C):
        """(dim, phi_(C, M)) of S_C(M) = C''/C' with the automorphism
        x + C' -> (C x cap C'') + C' (p. 139), on a complement of C'."""
        F = self.F
        lo, hi = self.band_part(C)
        k = sdim(lo)
        dd = sdim(hi) - k
        if dd == 0:
            return 0, None
        full = dense(lo).augment(dense(hi)) if lo.ncols() else dense(hi)
        B = full.matrix_from_columns(full.pivots())
        RA, RB = self.relation(C)
        lo_d, hi_d = dense(lo), dense(hi)
        n = self.n
        # (c, t, s): RA c - lo t = x, RB c - hi s = 0
        left = -lo_d if lo_d.ncols() else dmatrix(F, n, 0)
        top = RA.augment(left).augment(dmatrix(F, n, hi_d.ncols()))
        bot = RB.augment(dmatrix(F, n, lo_d.ncols())).augment(-hi_d)
        Sys = top.stack(bot)
        cols = []
        for j in range(k, B.ncols()):
            rhs = vector(F, list(B.column(j)) + [0] * n)
            sol = ssolve(Sys, rhs)
            y = smul(RB, sol[:RA.ncols()])
            cols.append(ssolve(B, y)[k:])
        return dd, dmatrix(F, cols).transpose()


def similar(P, Q):
    P, Q = dense(P), dense(Q)
    return P.nrows() == Q.nrows() and P.is_similar(Q)


