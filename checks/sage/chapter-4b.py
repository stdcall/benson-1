_MTX = {}


def mtx(name):
    if name not in _MTX:
        _MTX[name] = libgap.eval('MTX.' + name)
    return _MTX[name]


FAIL = libgap.eval('fail')


def gap_module(M):
    return libgap.GModuleByMats([libgap(dense(m)) for m in M.mats],
                                libgap.GF(M.A.F.order()))


def isomorphic(M, N):
    if M.dim != N.dim:
        return False
    if M.dim == 0:
        return True
    return mtx('IsomorphismModules')(gap_module(M), gap_module(N)) != FAIL


def _ffe(F, c):
    try:
        return F(c)
    except TypeError:
        # GAP's Z(q) and the generator of F are roots of the same Conway
        # polynomial
        return c.polynomial()(F.gen())


def to_sage_mat(F, X):
    return sp(dmatrix(F, [[_ffe(F, c) for c in row] for row in X.sage()]))


def decompose(M):
    """The indecomposable summands of M."""
    if M.dim == 0:
        return []
    out = []
    for x in mtx('Indecomposition')(gap_module(M)):
        gm = libgap.eval('x -> x.generators')(x[1])
        out.append(Mod(M.A, [to_sage_mat(M.A.F, X) for X in gm]))
    return out


def is_indecomposable(M):
    return bool(mtx('IsIndecomposable')(gap_module(M)))


def rad_end(M):
    """A basis of J(End M) for indecomposable M; the matrices commute with
    the action, so they are endomorphisms in our convention as well."""
    G = gap_module(M)
    assert mtx('IsIndecomposable')(G)
    sm = libgap.eval('x -> x.smashMeataxe')(G)
    return [to_sage_mat(M.A.F, X) for X in sm['basisEndoRad']]


def end_residue_dim(M):
    """dim_k End(M)/J End(M) for indecomposable M."""
    return hom_dim(M, M) - len(rad_end(M))


def find_iso(M, lst):
    for i, N in enumerate(lst):
        if isomorphic(M, N):
            return i
    return None


def strip(M, remove):
    return [X for X in decompose(M) if find_iso(X, remove) is None]


def multiset_iso(Xs, Ys):
    """The two lists of indecomposables agree up to isomorphism and order."""
    Ys = list(Ys)
    if len(Xs) != len(Ys):
        return False
    for X in Xs:
        i = find_iso(X, Ys)
        if i is None:
            return False
        Ys.pop(i)
    return True


def algebra_radical(A):
    """Coordinates of a basis of J(A) (GAP's RadicalOfAlgebra), cached."""
    if getattr(A, '_rad', None) is not None:
        return A._rad
    F = A.F
    alg = libgap.Algebra(libgap.GF(F.order()),
                         [libgap(dense(X)) for X in A.Lb])
    out = []
    for X in libgap.BasisVectors(libgap.Basis(libgap.RadicalOfAlgebra(alg))):
        out.append(to_sage_mat(F, X) * A.one)
    A._rad = out
    return out


def radical_of_module(M, Jx):
    Mb = basis_action(M)
    blocks = [element_action(M, x, Mb) for x in Jx]
    if not blocks:
        return zero_matrix(M.A.F, M.dim, 0)
    return colspace(block_matrix([blocks], subdivide=False))


def socle_of_module(M, Jx):
    Mb = basis_action(M)
    blocks = [element_action(M, x, Mb) for x in Jx]
    if not blocks:
        return identity_matrix(M.A.F, M.dim)
    return kernel_cols(block_matrix([[b] for b in blocks], subdivide=False))


def span_dim(F, mats):
    if not mats:
        return 0
    return dmatrix(F, [dense(X).list() for X in mats]).rank()


