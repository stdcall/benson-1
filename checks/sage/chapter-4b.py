def trivial_mod(A):
    return Mod(A, [identity_matrix(A.F, 1) for _ in A.names])


def gmod(A, mats):
    return Mod(A, [sp(dmatrix(A.F, m)) if not hasattr(m, 'nrows') else m
                   for m in mats])


def stable_hom_dim(M, N, ctx):
    """dim Hom-bar(M, N): Hom(M, N) modulo maps through the free cover of N
    (every map through a projective factors through it)."""
    F = M.A.F
    H = hom_space(M, N)
    if not H:
        return 0
    r, pi = free_cover(N)
    Fm = free_module(N.A, r)
    P = [pi * X for X in hom_space(M, Fm)]
    return span_dim(F, H + P) - span_dim(F, P)


def irr_dims(mods, F):
    """dim_k Irr(M_i, M_j) = Rad/Rad^2 over the given complete list of
    indecomposables (finite type)."""
    n = len(mods)
    R = {}
    for i in range(n):
        for j in range(n):
            R[i, j] = rad_end(mods[i]) if i == j else hom_space(mods[i],
                                                                mods[j])
    out = {}
    for i in range(n):
        for j in range(n):
            prods = [Y * X for k in range(n) for X in R[i, k]
                     for Y in R[k, j]]
            out[i, j] = len(R[i, j]) - span_dim(F, prods)
    return out


def count_iso(X, parts):
    return sum(1 for P in parts if isomorphic(P, X))


def species_algebra():
    """The GF(2)-algebra [[F, 0], [F', F']], F = GF(2), F' = GF(4): the
    tensor algebra of the bimodule F'_F (a species of type B_2), acting on
    F + F' = GF(2)^3."""
    F = GF(2)
    e1 = dmatrix(F, [[1, 0, 0], [0, 0, 0], [0, 0, 0]])
    e2 = dmatrix(F, [[0, 0, 0], [0, 1, 0], [0, 0, 1]])
    w = dmatrix(F, [[0, 0, 0], [0, 0, 1], [0, 1, 1]])   # multiplication by w
    beta = dmatrix(F, [[0, 0, 0], [1, 0, 0], [0, 0, 0]])
    return Alg(F, [e1, e2, w, beta], ['e1', 'e2', 'w', 'beta'], 'species')


