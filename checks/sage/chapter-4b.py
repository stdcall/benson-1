class Alg:
    """The unital algebra generated by matrices `gens` (acting on a faithful
    module), with its left regular representation on a basis of words in
    the generators.  Lb[j] is left multiplication by the basis element b_j,
    L[t] and R[t] left and right multiplication by the generator t."""

    def __init__(self, F, gens, names, name=''):
        self.F, self.names, self.name = F, list(names), name
        n = gens[0].nrows()
        I = identity_matrix(F, n)
        basis, words = [I], [()]
        rows = [dense(I).list()]
        frontier = [0]
        while frontier:
            cands, cwords = [], []
            for b in frontier:
                for t, g in enumerate(gens):
                    cands.append(sp(g * basis[b]))
                    cwords.append((t,) + words[b])
            stack = dmatrix(F, rows + [dense(c).list() for c in cands])
            new = []
            for p in stack.pivot_rows():
                if p >= len(rows):
                    k = p - len(rows)
                    basis.append(cands[k])
                    words.append(cwords[k])
                    new.append(len(basis) - 1)
            rows += [dense(basis[i]).list() for i in new]
            frontier = new
        self.dim = d = len(basis)
        self.fbasis, self.words = basis, words
        Bm = dmatrix(F, rows)
        self._piv = Bm.pivots()
        self._inv = sp(Bm.matrix_from_columns(self._piv).inverse())
        self.L = [sp(dmatrix(F, [self.coords(g * b) for b in basis])
                     .transpose()) for g in gens]
        self.Lb = []
        for w in words:
            A = identity_matrix(F, d)
            for t in reversed(w):
                A = self.L[t] * A
            self.Lb.append(A)
        self.one = vector(F, [1] + [0] * (d - 1))
        self.R = []
        for t in range(len(gens)):
            gco = self.L[t] * self.one
            self.R.append(sp(dmatrix(F, [self.Lb[i] * gco
                                         for i in range(d)]).transpose()))

    def coords(self, X):
        v = vector(self.F, dense(X).list())
        return vector(self.F, [v[p] for p in self._piv]) * self._inv

    def left_mult(self, x):
        A = zero_matrix(self.F, self.dim)
        for j, c in enumerate(x):
            if c:
                A += c * self.Lb[j]
        return A

    def regular(self):
        return Mod(self, list(self.L))

    def right_regular_dual(self):
        """D(A_A), a left module."""
        return Mod(self, [R.transpose() for R in self.R])

    def opposite(self):
        return Alg(self.F, list(self.R), self.names, self.name + '^op')


def group_alg(F, G, name='', gens=None):
    """The group algebra F G of a permutation group G on the basis of group
    elements; the algebra generators are gens (default G.gens())."""
    e = G.identity()
    gens = list(G.gens()) if gens is None else [G(g) for g in gens]
    els, words, idx = [e], [()], {e: 0}
    frontier = [0]
    while frontier:
        new = []
        for b in frontier:
            for t, g in enumerate(gens):
                c = g * els[b]
                if c not in idx:
                    idx[c] = len(els)
                    els.append(c)
                    words.append((t,) + words[b])
                    new.append(idx[c])
        frontier = new
    n = len(els)
    A = Alg.__new__(Alg)
    A.F, A.names, A.name, A.dim = F, ['g%d' % t for t in range(len(gens))], \
        name, n
    A.words, A.els, A.idx, A.G = words, els, idx, G
    A.gens_list = gens

    def perm(f):
        P = zero_matrix(F, n)
        for j, x in enumerate(els):
            P[idx[f(x)], j] = 1
        return P
    A.Lb = [perm(lambda x, g=g: g * x) for g in els]
    A.L = [A.Lb[idx[g]] for g in gens]
    A.R = [perm(lambda x, g=g: x * g) for g in gens]
    A.one = vector(F, [1] + [0] * (n - 1))
    A.fbasis = None
    return A


class Mod:
    def __init__(self, A, mats):
        self.A, self.mats = A, [sp(m) for m in mats]
        self.dim = mats[0].nrows() if mats else 0


def is_group_module(M):
    """The matrices of the generators define a module of the group algebra:
    g_t b_j = b_(g_t x_j) on the basis of group elements."""
    A = M.A
    Mb = basis_action(M)
    for t, g in enumerate(A.gens_list):
        for j, x in enumerate(A.els):
            if M.mats[t] * Mb[j] != Mb[A.idx[g * x]]:
                return False
    return True


