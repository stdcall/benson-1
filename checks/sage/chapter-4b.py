class BrauerGraph:
    """A Brauer graph: cyc[v] = edges round the vertex v in cyclic order,
    mult[v] its multiplicity.  The projective P_j (Definition, p. 166) has
    the top t, for each end v of j a uniserial chain whose composition
    factors are the edges after j round v, mult[v] times, without the last
    j, and the socle s; the arrows of the Ext-quiver go round the vertices
    (p. 167).  lam[(j, v)] scales the last arrow of the chain of P_j at v."""

    def __init__(self, F, cyc, mult, lam=None):
        self.F, self.cyc, self.mult = F, cyc, mult
        lam = lam or {}
        self.edges = sorted({j for v in cyc for j in cyc[v]})
        self.arrows = []                      # (v, i, source, target)
        for v in sorted(cyc):
            c = cyc[v]
            if len(c) > 1 or mult.get(v, 1) > 1:
                for i in range(len(c)):
                    self.arrows.append((v, i, c[i], c[(i + 1) % len(c)]))
        aidx = {(a[0], a[1]): t for t, a in enumerate(self.arrows)}
        # basis vectors: (j, 'top'), (j, v, k), (j, 'soc'); with factors
        self.basis, self.factor = [], []
        self.chains = {}
        for j in self.edges:
            self.basis.append((j, 'top'))
            self.factor.append(j)
            for v in sorted(cyc):
                if j not in cyc[v]:
                    continue
                c, pos = cyc[v], cyc[v].index(j)
                L = mult.get(v, 1) * len(c) - 1
                ch = []
                for k in range(1, L + 1):
                    self.basis.append((j, v, k))
                    self.factor.append(c[(pos + k) % len(c)])
                    ch.append(c[(pos + k) % len(c)])
                self.chains[j, v] = ch
            self.basis.append((j, 'soc'))
            self.factor.append(j)
        idx = {b: i for i, b in enumerate(self.basis)}
        self.idx = idx
        n = len(self.basis)
        mats = []
        for j in self.edges:
            e = zero_matrix(F, n)
            for i, fct in enumerate(self.factor):
                if fct == j:
                    e[i, i] = 1
            mats.append(e)
        arrow_mats = [zero_matrix(F, n) for _ in self.arrows]
        for j in self.edges:
            for v in sorted(cyc):
                if j not in cyc[v] or (v, cyc[v].index(j)) not in aidx:
                    continue
                c, pos = cyc[v], cyc[v].index(j)
                L = len(self.chains[j, v])
                prev = (j, 'top')
                for k in range(1, L + 1):
                    t = aidx[v, (pos + k - 1) % len(c)]
                    arrow_mats[t][idx[j, v, k], idx[prev]] = 1
                    prev = (j, v, k)
                t = aidx[v, (pos + L) % len(c)]
                arrow_mats[t][idx[j, 'soc'], idx[prev]] = lam.get((j, v), 1)
        self.gens = mats + arrow_mats
        self.names = ['e%d' % j for j in self.edges] + \
            ['%s%d' % (a[0], a[1]) for a in self.arrows]
        self.A = Alg(F, self.gens, self.names, 'Brauer graph algebra')
        self.whole = Mod(self.A, self.gens)
        self.P = {}
        for j in self.edges:
            cols = [i for i, b in enumerate(self.basis) if b[0] == j]
            B = dmatrix(F, n, len(cols))
            for c_, i in enumerate(cols):
                B[i, c_] = 1
            self.P[j] = submodule(self.whole, B)
            self.P[j].cols = cols

    def arrow(self, v, i):
        t = [k for k, a in enumerate(self.arrows) if a[0] == v and a[1] == i]
        return self.gens[len(self.edges) + t[0]]

    def simple(self, j):
        mats = [zero_matrix(self.F, 1) for _ in self.gens]
        mats[self.edges.index(j)] = identity_matrix(self.F, 1)
        return Mod(self.A, mats)

    def quotient_of_P(self, j, keep):
        """P_j modulo the span of the basis vectors of P_j not in keep."""
        cols = self.P[j].cols
        drop = [c_ for c_, i in enumerate(cols) if self.basis[i] not in keep]
        B = dmatrix(self.F, len(cols), len(drop))
        for k, c_ in enumerate(drop):
            B[c_, k] = 1
        Q, proj = quotient(self.P[j], sp(B))
        return Q, proj

    def sub_of_P(self, j, keep):
        cols = self.P[j].cols
        sel = [c_ for c_, i in enumerate(cols) if self.basis[i] in keep]
        B = dmatrix(self.F, len(cols), len(sel))
        for k, c_ in enumerate(sel):
            B[c_, k] = 1
        return submodule(self.P[j], sp(B))


def symmetric_forms(A):
    """Linear forms vanishing on [A, A] (rows), and the multiplication
    table data needed for their Gram matrices."""
    F, d = A.F, A.dim
    comm = []
    for i in range(d):
        for j in range(i + 1, d):
            comm.append(A.Lb[i].column(j) - A.Lb[j].column(i))
    Cm = dmatrix(F, comm)
    return Cm.right_kernel().basis_matrix()


def gram(A, wv):
    return dmatrix(A.F, [wv * A.Lb[i] for i in range(A.dim)])


def tube_quiver(seqs, mods):
    """The stable Auslander-Reiten quiver from almost split sequences."""
    V = list(range(len(mods)))
    A, tau = set(), {}
    for i, (tidx, parts, soc, E, M, sigma) in seqs.items():
        tau[i] = tidx
        for X in parts:
            j = find_iso(X, mods)
            if j is not None:
                A.add((j, i))
                A.add((tidx, j))
    return TQ(V, A, tau)


