def colspace(B):
    """A matrix whose columns are a basis of the column space of B."""
    B = dense(B)
    if B.ncols() == 0:
        return sp(B)
    E = B.transpose().echelon_form()
    return sp(E.matrix_from_rows(range(E.rank())).transpose())


def kernel_cols(A):
    """Columns: a basis of the right kernel of A."""
    return sp(dense(A).right_kernel().basis_matrix().transpose())


def in_span(B, v):
    B = dense(B)
    if B.ncols() == 0:
        return dense(v).is_zero()
    return B.rank() == B.augment(dense(v)).rank()


def smul(A, B):
    """A product that avoids dense products in odd characteristic."""
    return sp(A) * (sp(B) if hasattr(B, 'nrows') else B)


def ssolve(A, B):
    """A solution X of A X = B (sparse in odd characteristic)."""
    return sp(A).solve_right(sp(B) if hasattr(B, 'nrows') else B)


def rank(A):
    return dense(A).rank() if A.ncols() and A.nrows() else 0


