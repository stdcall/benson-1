def transpose_right_action(N):
    """Tr N = Coker(f^* : Hom(P_0, A) -> Hom(P_1, A)) for a free
    presentation P_1 -> P_0 -> N -> 0 (p. 145): the matrices of the right
    action of the generators on Tr N (v -> v g)."""
    A = N.A
    F, d = A.F, A.dim
    Fm, K, pi, r0 = kernel_module(N)
    Kd = dense(K)
    kgens = [vector(F, dense(smul(Kd, dmatrix(F, v).transpose())).column(0))
             for v in generators_of(submodule(Fm, K))]
    r1 = len(kgens)
    cols = []
    for i in range(r0):
        for m in range(d):
            out = []
            for k in kgens:
                out += list(A.left_mult(k[i * d:(i + 1) * d]) * A.Lb[m]
                            * A.one)
            cols.append(out)
    Fstar = dmatrix(F, cols).transpose()
    Rr = [block_matrix([[A.R[t] if i == j else zero_matrix(F, d)
                         for j in range(r1)] for i in range(r1)],
                       subdivide=False) for t in range(len(A.names))]
    Q, _ = quotient(Mod(A, Rr), sp(Fstar))
    return Q.mats


class Context:
    """An algebra with its indecomposable projective and injective modules
    and the radical."""

    def __init__(self, A, radical=False):
        self.A = A
        self.Aop = None
        self.proj = []
        for X in decompose(A.regular()):
            if find_iso(X, self.proj) is None:
                self.proj.append(X)
        self.inj = []
        for X in decompose(A.right_regular_dual()):
            if find_iso(X, self.inj) is None:
                self.inj.append(X)
        self.J = algebra_radical(A) if radical else None

    def is_projective(self, M):
        return find_iso(M, self.proj) is not None

    def is_injective(self, M):
        return find_iso(M, self.inj) is not None

    def DTr_free(self, N):
        return Mod(N.A, [X.transpose() for X in transpose_right_action(N)])

    def DTr(self, N):
        parts = strip(self.DTr_free(N), self.inj)
        return direct_sum(*parts) if parts else zero_mod(self.A)

    def TrD(self, M):
        if self.Aop is None:
            self.Aop = self.A.opposite()
        Dm = Mod(self.Aop, [X.transpose() for X in M.mats])
        X = Mod(self.A, transpose_right_action(Dm))
        parts = strip(X, self.proj)
        return direct_sum(*parts) if parts else zero_mod(self.A)

    def omega(self, M, k=1):
        for _ in range(k):
            Fm, K, pi, r = kernel_module(M)
            parts = strip(submodule(Fm, K), self.proj)
            M = direct_sum(*parts) if parts else zero_mod(self.A)
            if M.dim == 0:
                return M
        return M

    def omega_inv(self, M, k=1):
        """Omega^-1 (A self-injective): the dual of Omega of the dual."""
        if self.Aop is None:
            self.Aop = self.A.opposite()
        for _ in range(k):
            Dm = Mod(self.Aop, [X.transpose() for X in M.mats])
            Fm, K, pi, r = kernel_module(Dm)
            S = submodule(Fm, K)
            X = Mod(self.A, [Y.transpose() for Y in S.mats])
            parts = strip(X, self.inj)
            M = direct_sum(*parts) if parts else zero_mod(self.A)
        return M

    def omega_min(self, M, tops):
        """Omega(M) as the kernel of a projective cover built from the
        projective indecomposables (tops[i] the top of proj[i], End = k);
        for a self-injective algebra and M without projective summands it
        has no projective summand."""
        return cover_kernel(M, self.proj, tops)

    def nakayama(self, M):
        """nu(M) = D Hom_A(M, A) (Remark after Proposition 4.12.9)."""
        A = self.A
        H = hom_space(M, A.regular())
        if not H:
            return zero_mod(A)
        Hm = dmatrix(A.F, [dense(h).list() for h in H]).transpose()
        mats = []
        for t in range(len(A.names)):
            cols = [ssolve(Hm, vector(A.F, dense(A.R[t] * h).list()))
                    for h in H]
            mats.append(sp(dmatrix(A.F, cols).transpose()).transpose())
        return Mod(A, mats)


def cover_kernel(M, projs, tops):
    """The kernel of a projective cover sum P_j^(m_j) -> M, m_j the
    multiplicity of the simple tops[j] (with End = k) in the top of M; the
    surjection is a random combination of homomorphisms (retried)."""
    F = M.A.F
    mult = [hom_dim(M, S) for S in tops]
    cover = [projs[j] for j in range(len(projs)) for _ in range(mult[j])]
    if not cover:
        return zero_mod(M.A)
    Hs = [hom_space(Q, M) for Q in cover]
    # greedy: for each copy take the basis map (or sum of two) adding most
    # to the image modulo the images chosen so far
    blocks = []
    acc = zero_matrix(F, M.dim, 0)
    for H in Hs:
        cands = list(H) + [H[a] + H[b] for a in range(len(H))
                           for b in range(a + 1, len(H))]
        best = max(cands, key=lambda h: rank(acc.augment(h)))
        blocks.append(best)
        acc = acc.augment(best)
    f = block_matrix([blocks], subdivide=False)
    if rank(f) != M.dim:
        for _ in range(200):
            blocks = []
            for H in Hs:
                X = zero_matrix(F, M.dim, H[0].ncols())
                for h in H:
                    X += rnd(F) * h
                blocks.append(X)
            f = block_matrix([blocks], subdivide=False)
            if rank(f) == M.dim:
                break
    assert rank(f) == M.dim, 'no surjection found'
    return submodule(direct_sum(*cover), kernel_cols(f))


def _unvec(F, v, rows, cols):
    return sp(dmatrix(F, rows, cols, list(v)))


def ar_sequence(ctx, N, M=None):
    """The almost split sequence 0 -> M -> E -> N -> 0, M = D Tr N, built as
    in the text (p. 144): an extension representing a non-zero element of
    the socle of Ext^1(N, M) as a right End(N)-module.  Ext^1 is computed
    from 0 -> K -> A^r -> N -> 0, the action of End(N) by lifting to A^r.
    Returns (M, E, iota, sigma, dimension of the socle)."""
    A = ctx.A
    F, d = A.F, A.dim
    if M is None:
        M = ctx.DTr(N)
    Fm, K, pi, r = kernel_module(N)
    Kmod = submodule(Fm, K)
    H = hom_space(Kmod, M)
    assert H, 'Ext^1 vanishes'

    def vec(X):
        return vector(F, dense(X).list())
    Kd = dense(K)
    piv = Kd.transpose().pivots()
    Ksol = sp(Kd.matrix_from_rows(piv).inverse())
    Hmat = dmatrix(F, [vec(h) for h in H]).transpose()
    Mb = basis_action(M)
    res = []
    for i in range(r):
        for v in _identity_matrix(F, M.dim).columns():
            Phi = zero_matrix(F, M.dim, r * d)
            vv = sp(dmatrix(F, v).transpose())
            for m in range(d):
                Phi.set_column(i * d + m, dense(Mb[m] * vv).column(0))
            res.append(vec(Phi * K))
    Res = dmatrix(F, res).transpose()
    gensN = generators_of(N)
    pid = dense(pi)
    lifts = []
    for Y in rad_end(N):
        fi = [vector(F, dense(ssolve(pid, Y * sp(dmatrix(F, v)
                                                    .transpose()))).column(0))
              for v in gensN]
        Rt = zero_matrix(F, r * d)
        for i in range(r):
            for m in range(d):
                Rt.set_column(i * d + m, free_lb(A, r, m) * fi[i])
        lifts.append(Ksol * sp(dense(Rt * K).matrix_from_rows(piv)))
    P = Res.transpose().right_kernel().basis_matrix()
    if lifts:
        Cond = block_matrix(
            [[smul(P, dmatrix(F, [vec(h * RK) for h in H]).transpose())]
             for RK in lifts], subdivide=False)
        Sc = Cond.right_kernel().basis_matrix()
    else:
        Sc = _identity_matrix(F, len(H))
    Svecs = [smul(Hmat, c) for c in dense(Sc).rows()]
    soc = dmatrix(F, Svecs).transpose().augment(Res).rank() - Res.rank()
    hvec = next(s for s in Svecs
                if not in_span(Res, dmatrix(F, s).transpose()))
    h = _unvec(F, hvec, M.dim, Kmod.dim)
    E, proj = quotient(direct_sum(M, Fm), sp(dense(h).stack(-Kd)))
    iota = proj * sp(_identity_matrix(F, M.dim).stack(
        dmatrix(F, r * d, M.dim)))
    sigma_full = dmatrix(F, N.dim, M.dim).augment(pid)
    sec = ssolve(proj, _identity_matrix(F, E.dim))
    sigma = smul(sigma_full, sec)
    return M, E, iota, sigma, soc


def ar_hom_criterion(M, E, N, tests, fN, fM):
    """Proposition 4.12.6 for the test modules X (indecomposable):
    dim Hom(X, E) - dim Hom(X, M) = dim Hom(X, N) - [X = N] f_N and
    dim Hom(E, X) - dim Hom(N, X) = dim Hom(M, X) - [X = M] f_M."""
    for X in tests:
        a = hom_dim(X, E) - hom_dim(X, M)
        b = hom_dim(X, N) - (fN if isomorphic(X, N) else 0)
        c = hom_dim(E, X) - hom_dim(N, X)
        e = hom_dim(M, X) - (fM if isomorphic(X, M) else 0)
        if a != b or c != e:
            return False
    return True


def sigma_splits(N, E, sigma):
    """Is there a module map s : N -> E with sigma s = 1?"""
    S = hom_space(N, E)
    if not S:
        return False
    F = N.A.F
    imgs = dmatrix(F, [dense(sigma * s).list() for s in S]).transpose()
    target = dmatrix(F, dense(identity_matrix(F, N.dim)).list()).transpose()
    return in_span(imgs, target)


class _SubAlg:
    def __init__(self, F, k):
        self.F, self.names = F, ['h%d' % i for i in range(k)]


def restrict_to(M, words):
    """Restriction of a module of a group algebra to the subgroup generated
    by the elements with the given words in the generators."""
    mats = []
    for w in words:
        X = identity_matrix(M.A.F, M.dim)
        for t in reversed(w):
            X = M.mats[t] * X
        mats.append(X)
    return Mod(_SubAlg(M.A.F, len(mats)), mats)


def knit(ctx, start_mods, limit=60, tau=None):
    """The modules reached from start_mods by D Tr, Tr D and middle terms of
    almost split sequences (Section 4.13): returns (list of non-projective
    indecomposables, dict index -> (tau index, middle summands))."""
    mods, seqs = [], {}
    queue = []
    for M in start_mods:
        if not ctx.is_projective(M) and find_iso(M, mods) is None:
            mods.append(M)
            queue.append(len(mods) - 1)
    while queue:
        i = queue.pop(0)
        N = mods[i]
        M, E, iota, sigma, soc = ar_sequence(
            ctx, N, M=None if tau is None else tau(N))
        parts = decompose(E)
        for X in [M] + parts:
            if not ctx.is_projective(X) and find_iso(X, mods) is None:
                mods.append(X)
                queue.append(len(mods) - 1)
                assert len(mods) <= limit, 'too many modules'
        seqs[i] = (find_iso(M, mods), parts, soc, E, M, sigma)
    return mods, seqs


