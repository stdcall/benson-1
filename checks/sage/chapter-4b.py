        Mi, Ei, Ni = induce(M), induce(E), induce(kH)
        dM, dE, dN = decompose(Mi), decompose(Ei), decompose(Ni)
        # Omega^2 f(M) up = Omega^2 M + Y1, f(M) up = M + Y2, and
